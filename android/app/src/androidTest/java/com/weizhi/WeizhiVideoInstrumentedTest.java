package com.weizhi;

import android.content.Context;
import android.media.MediaCodec;
import android.media.MediaCodecInfo;
import android.media.MediaFormat;
import android.media.MediaMuxer;

import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.platform.app.InstrumentationRegistry;

import com.weizhi.video.WeizhiVideo;

import org.junit.Test;
import org.junit.runner.RunWith;

import java.io.File;
import java.nio.ByteBuffer;
import java.util.concurrent.TimeUnit;

import static org.junit.Assert.assertTrue;

/**
 * On-device P1 gate for the bundled weizhi_video plugin (docs/video-architecture.md):
 * probe / trim / concat via the NDK media stack, driven end-to-end from JS.
 * Fixtures are deterministic all-intra AVC files generated by MediaCodec so the
 * suite needs no committed media binaries.
 */
@RunWith(AndroidJUnit4.class)
public final class WeizhiVideoInstrumentedTest {
    private static final int WIDTH = 320;
    private static final int HEIGHT = 240;
    private static final int FPS = 30;
    private static final int FIXTURE_MS = 1000;

    @Test
    public void probeTrimAndConcat() throws Exception {
        Context context = InstrumentationRegistry.getInstrumentation().getTargetContext();
        File ws = new File(context.getCacheDir(), "weizhi-media-" + System.currentTimeMillis());
        assertTrue(ws.mkdirs());
        File a = new FixtureEncoder(ws, "a.mp4", FIXTURE_MS, 40).run();
        File b = new FixtureEncoder(ws, "b.mp4", FIXTURE_MS, 180).run();
        assertTrue(a.length() > 0);
        assertTrue(b.length() > 0);

        try (WeizhiEngine engine = new WeizhiEngine()) {
            engine.setFsRoot(ws.getAbsolutePath());
            WeizhiVideo.install(engine);
            String out = engine.runJs(
                    "const v = await host.ensureNative('video');"
                            + "const pa = JSON.parse(v.probe('a.mp4'));"
                            + "const job = v.open_job(JSON.stringify({"
                            + "  clips: [{path: 'a.mp4', startMs: 200, endMs: 800}, {path: 'b.mp4'}],"
                            + "  output: 'out.mp4'}));"
                            + "const events = [];"
                            + "const r = JSON.parse(v.run_job(job, (e) => { events.push(e); }));"
                            + "v.close_job(job);"
                            + "const po = JSON.parse(v.probe('out.mp4'));"
                            + "({aTracks: pa.tracks.length, aDur: pa.durationMs, aW: pa.tracks[0].width,"
                            + "  ok: r.ok, outTracks: po.tracks.length, outDur: po.durationMs,"
                            + "  events: events.length,"
                            + "  lastPercent: events.length ? events[events.length - 1].percent : -1})",
                    30_000);
            assertTrue(out, out.contains("\"aTracks\":1"));
            assertTrue(out, out.contains("\"aW\":320"));
            assertTrue(out, out.contains("\"ok\":true"));
            assertTrue(out, out.contains("\"outTracks\":1"));
            /* trim 600ms + full 1000ms fixture, codec/muxer slop allowed */
            int aDur = jsonInt(out, "aDur");
            assertTrue("aDur=" + aDur, aDur > 800 && aDur < 1300);
            int outDur = jsonInt(out, "outDur");
            assertTrue("outDur=" + outDur, outDur > 1300 && outDur < 2100);
            assertTrue("no progress events", jsonInt(out, "events") >= 1);
        }
    }

    private static int jsonInt(String json, String key) {
        java.util.regex.Matcher m =
                java.util.regex.Pattern.compile("\"" + key + "\":(-?\\d+)").matcher(json);
        assertTrue("missing " + key + " in " + json, m.find());
        return Integer.parseInt(m.group(1));
    }

    /**
     * Deterministic all-intra AVC fixture: every frame is a sync frame filled with a
     * solid luma value, so trim boundaries land exactly on the pts grid.
     */
    private static final class FixtureEncoder {
        private final File file;
        private final int frames;
        private final int luma;
        private MediaCodec codec;
        private MediaMuxer muxer;
        private int track = -1;
        private boolean muxStarted;

        FixtureEncoder(File dir, String name, int durationMs, int luma) {
            this.file = new File(dir, name);
            this.frames = (int) Math.round(durationMs / 1000.0 * FPS);
            this.luma = luma;
        }

        File run() throws Exception {
            MediaFormat fmt =
                    MediaFormat.createVideoFormat(MediaFormat.MIMETYPE_VIDEO_AVC, WIDTH, HEIGHT);
            fmt.setInteger(MediaFormat.KEY_COLOR_FORMAT,
                    MediaCodecInfo.CodecCapabilities.COLOR_FormatYUV420Flexible);
            fmt.setInteger(MediaFormat.KEY_BIT_RATE, 2_000_000);
            fmt.setInteger(MediaFormat.KEY_FRAME_RATE, FPS);
            fmt.setInteger(MediaFormat.KEY_I_FRAME_INTERVAL, 0);
            codec = MediaCodec.createEncoderByType(MediaFormat.MIMETYPE_VIDEO_AVC);
            codec.configure(fmt, null, null, MediaCodec.CONFIGURE_FLAG_ENCODE);
            codec.start();
            muxer = new MediaMuxer(file.getAbsolutePath(),
                    MediaMuxer.OutputFormat.MUXER_OUTPUT_MPEG_4);
            try {
                long frameUs = TimeUnit.SECONDS.toMicros(1) / FPS;
                for (int i = 0; i < frames; i++) {
                    int inIdx = codec.dequeueInputBuffer(10_000);
                    assertTrue("encoder input timeout", inIdx >= 0);
                    fillYuvFrame(inIdx);
                    codec.queueInputBuffer(inIdx, 0, WIDTH * HEIGHT * 3 / 2, i * frameUs, 0);
                    drain(false);
                }
                int eosIdx = codec.dequeueInputBuffer(10_000);
                assertTrue("encoder eos input timeout", eosIdx >= 0);
                codec.queueInputBuffer(eosIdx, 0, 0, 0, MediaCodec.BUFFER_FLAG_END_OF_STREAM);
                drain(true);
                assertTrue("track never configured", track >= 0);
                return file;
            } finally {
                try {
                    if (muxStarted) {
                        muxer.stop();
                    }
                } finally {
                    muxer.release();
                    codec.stop();
                    codec.release();
                }
            }
        }

        private void fillYuvFrame(int index) {
            android.media.Image image = codec.getInputImage(index);
            assertTrue(image != null);
            android.media.Image.Plane[] planes = image.getPlanes();
            for (int p = 0; p < planes.length; p++) {
                ByteBuffer buf = planes[p].getBuffer();
                buf.rewind();
                byte fill = (byte) (p == 0 ? luma : 128);
                while (buf.hasRemaining()) {
                    buf.put(fill);
                }
            }
            image.close();
        }

        private void drain(boolean eos) throws Exception {
            MediaCodec.BufferInfo info = new MediaCodec.BufferInfo();
            while (true) {
                int idx = codec.dequeueOutputBuffer(info, eos ? 10_000 : 0);
                if (idx == MediaCodec.INFO_TRY_AGAIN_LATER) {
                    if (eos) {
                        throw new IllegalStateException("encoder EOS timeout");
                    }
                    return;
                }
                if (idx == MediaCodec.INFO_OUTPUT_FORMAT_CHANGED) {
                    track = muxer.addTrack(codec.getOutputFormat());
                    muxer.start();
                    muxStarted = true;
                    continue;
                }
                if (idx < 0) {
                    continue;
                }
                if (info.size > 0 && (info.flags & MediaCodec.BUFFER_FLAG_CODEC_CONFIG) == 0
                        && muxStarted) {
                    ByteBuffer data = codec.getOutputBuffer(idx);
                    data.position(info.offset);
                    data.limit(info.offset + info.size);
                    MediaCodec.BufferInfo write = new MediaCodec.BufferInfo();
                    write.set(0, info.size, info.presentationTimeUs,
                            info.flags & MediaCodec.BUFFER_FLAG_KEY_FRAME);
                    muxer.writeSampleData(track, data, write);
                }
                codec.releaseOutputBuffer(idx, false);
                if ((info.flags & MediaCodec.BUFFER_FLAG_END_OF_STREAM) != 0) {
                    return;
                }
            }
        }
    }
}
